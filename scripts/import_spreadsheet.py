"""Generate a SQL import from the original wedding spreadsheet (.ods).

Usage:
    python scripts/import_spreadsheet.py path/to/Book.ods -o import.local.sql

Then paste the output in Supabase: SQL Editor > New query > Run.
The output contains personal data, so it is gitignored (*.local.sql).
"""

import argparse
import xml.etree.ElementTree as ET
import zipfile

NS = {
    "table": "urn:oasis:names:tc:opendocument:xmlns:table:1.0",
    "text": "urn:oasis:names:tc:opendocument:xmlns:text:1.0",
    "office": "urn:oasis:names:tc:opendocument:xmlns:office:1.0",
}
T = "{%s}" % NS["table"]
O = "{%s}" % NS["office"]

# Section headers in "Detalhes do Orçamento" -> category names shown in the app.
WEDDING_CATEGORIES = {
    "RECEPÇÃO": "Recepção",
    "VESTIMENTA": "Vestimenta",
    "FLORES E DECORAÇÕES": "Flores e Decorações",
    "MÚSICA": "Música",
    "FOTOGRAFIAS E VÍDEOS": "Fotografias e Vídeo",
    "LEMBRANÇAS E PRESENTES": "Lembranças e Presentes",
    "CERIMÔNIA": "Cerimônia",
    "PAPELARIA": "Papelaria",
    "ALIANÇAS DE CASAMENTO": "Alianças de Casamento",
    "TRANSPORTE": "Transporte",
}

# Section titles in the extra sheet -> project name.
EXTRA_PROJECTS = {"Apartamento": "Apartamento", "Viagem": "Viagem"}


def read_sheets(path):
    """Return {sheet name: [row as list of (text, numeric value or None)]}."""
    root = ET.fromstring(zipfile.ZipFile(path).read("content.xml"))
    sheets = {}
    for table in root.iter(T + "table"):
        rows = []
        for row in table.iter(T + "table-row"):
            repeat = int(row.get(T + "number-rows-repeated", "1"))
            cells = []
            for cell in row:
                if cell.tag not in (T + "table-cell", T + "covered-table-cell"):
                    continue
                count = min(int(cell.get(T + "number-columns-repeated", "1")), 30)
                text = " ".join("".join(p.itertext()) for p in cell.findall("text:p", NS)).strip()
                value = cell.get(O + "value")
                cells += [(text, float(value) if value is not None else None)] * count
            while cells and not cells[-1][0]:
                cells.pop()
            # The sheets leave column A empty; start each row at its first filled cell.
            while cells and not cells[0][0]:
                cells.pop(0)
            if repeat < 50:
                rows += [cells] * repeat
        sheets[table.get(T + "name")] = rows
    return sheets


def find_sheet(sheets, prefix):
    for name, rows in sheets.items():
        if name.startswith(prefix):
            return rows
    raise SystemExit(f"Sheet starting with {prefix!r} not found")


def parse_details(rows):
    """Categories and items from the wedding details sheet."""
    categories = []
    current = None
    for cells in rows:
        if not cells:
            continue
        first = cells[0][0]
        if first in WEDDING_CATEGORIES:
            current = {"name": WEDDING_CATEGORIES[first], "items": []}
            categories.append(current)
        elif current and first and first.upper() != "TOTAL":
            estimated = cells[1] if len(cells) > 1 else ("", None)
            actual = cells[2] if len(cells) > 2 else ("", None)
            included = estimated[0].lower() == "incluso"
            if actual[1]:
                status = "closed"
            elif included:
                status = "included"
            else:
                status = "to_define"
            current["items"].append(
                {
                    "name": first,
                    "estimated": None if included else estimated[1],
                    "actual": actual[1],
                    "status": status,
                }
            )
        elif first.upper() == "TOTAL":
            current = None
    return categories


def parse_extra(rows):
    """Apartment / trip lists from the extra sheet."""
    projects = []
    current = None
    for cells in rows:
        if not cells:
            continue
        first = cells[0][0]
        if first in EXTRA_PROJECTS:
            current = {"name": EXTRA_PROJECTS[first], "items": []}
            projects.append(current)
        elif current and first and first != "CATEGORIA" and not first.startswith("Total"):
            estimated = cells[1][1] if len(cells) > 1 else None
            current["items"].append(
                {"name": first, "estimated": estimated, "actual": None, "status": "to_define"}
            )
    return projects


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def sql_number(value):
    return "null" if value is None else f"{value:.2f}"


def build_sql(projects):
    lines = [
        "-- Import from the original spreadsheet. Generated by scripts/import_spreadsheet.py.",
        "do $$",
        "declare",
        "  v_wedding uuid;",
        "  v_project uuid;",
        "  v_category uuid;",
        "begin",
        "  if (select count(*) from public.weddings) <> 1 then",
        "    raise exception 'Expected exactly one wedding, found %', (select count(*) from public.weddings);",
        "  end if;",
        "  select id into v_wedding from public.weddings;",
        "",
        "  if exists (select 1 from public.projects where wedding_id = v_wedding) then",
        "    raise exception 'This wedding already has projects. Import skipped to avoid duplicates.';",
        "  end if;",
    ]
    for p_index, project in enumerate(projects):
        lines += [
            "",
            f"  insert into public.projects (wedding_id, name, position)",
            f"  values (v_wedding, {sql_text(project['name'])}, {p_index}) returning id into v_project;",
        ]
        for c_index, category in enumerate(project["categories"]):
            lines += [
                f"  insert into public.categories (wedding_id, project_id, name, position)",
                f"  values (v_wedding, v_project, {sql_text(category['name'])}, {c_index}) returning id into v_category;",
            ]
            if category["items"]:
                values = ",\n".join(
                    f"    (v_wedding, v_category, {sql_text(item['name'])}, {sql_number(item['estimated'])}, "
                    f"{sql_number(item['actual'])}, '{item['status']}', {i_index})"
                    for i_index, item in enumerate(category["items"])
                )
                lines += [
                    "  insert into public.budget_items",
                    "    (wedding_id, category_id, name, estimated_amount, actual_amount, status, position)",
                    "  values",
                    values + ";",
                ]
    lines += ["end;", "$$;", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("ods")
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()

    sheets = read_sheets(args.ods)
    wedding = {"name": "Casamento", "categories": parse_details(find_sheet(sheets, "Detalhes"))}
    extras = [
        {"name": p["name"], "categories": [{"name": p["name"], "items": p["items"]}]}
        for p in parse_extra(find_sheet(sheets, "Planilha1"))
    ]
    projects = [wedding] + extras

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(build_sql(projects))

    for project in projects:
        items = sum(len(c["items"]) for c in project["categories"])
        total = sum(i["estimated"] or 0 for c in project["categories"] for i in c["items"])
        print(f"{project['name']}: {len(project['categories'])} categories, {items} items, estimated {total:,.2f}")


if __name__ == "__main__":
    main()
